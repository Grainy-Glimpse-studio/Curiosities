/**
 * Convert simplified Chinese to traditional Chinese
 */
export function simplifiedToTraditional(text: string): string {
  let result = '';
  for (const char of text) {
    result += SIMPLIFIED_TO_TRADITIONAL[char] || char;
  }
  return result;
}

/**
 * Check if text contains Chinese characters
 */
export function containsChinese(text: string): boolean {
  return /[\u4e00-\u9fff]/.test(text);
}

/**
 * Check if text contains Japanese characters (hiragana/katakana)
 */
export function containsJapanese(text: string): boolean {
  return /[\u3040-\u30ff]/.test(text);
}

/**
 * Check if text is primarily Chinese (more than 30% Chinese characters)
 */
export function isPrimarilyChinese(text: string): boolean {
  const chineseChars = (text.match(/[\u4e00-\u9fff]/g) || []).length;
  const totalChars = text.replace(/\s/g, '').length;
  return totalChars > 0 && chineseChars / totalChars > 0.3;
}

/**
 * Check if text is primarily Japanese
 */
export function isPrimarilyJapanese(text: string): boolean {
  const japaneseChars = (text.match(/[\u3040-\u30ff]/g) || []).length;
  const totalChars = text.replace(/\s/g, '').length;
  return totalChars > 0 && japaneseChars / totalChars > 0.1;
}

/**
 * Check if text should be displayed vertically (Chinese or Japanese)
 */
export function shouldDisplayVertically(text: string): boolean {
  return isPrimarilyChinese(text) || isPrimarilyJapanese(text);
}

/**
 * Check if text is classical Chinese poetry (古诗)
 * Characteristics:
 * - Short sentences separated by commas and periods
 * - Regular meter (5 or 7 characters per half-line)
 * - Contains classical punctuation (，。)
 */
export function isClassicalPoetry(text: string): boolean {
  // Split by punctuation
  const segments = text.split(/[，。、；：！？]/g).filter(s => s.trim());

  if (segments.length < 2) return false;

  // Check if segments have regular length (5 or 7 characters typical for poetry)
  const lengths = segments.map(s => s.trim().length);
  const avgLength = lengths.reduce((a, b) => a + b, 0) / lengths.length;

  // Classical poetry typically has 5 or 7 character lines
  if (avgLength >= 4 && avgLength <= 8) {
    // Check if most lines have similar length (within ±2 chars)
    const regularLines = lengths.filter(l => Math.abs(l - avgLength) <= 2);
    return regularLines.length / lengths.length > 0.7;
  }

  return false;
}

/**
 * Split text into segments by punctuation for vertical display
 */
export function splitByPunctuation(text: string): string[] {
  // Split by Chinese punctuation, keeping the punctuation with the segment
  const segments: string[] = [];
  let current = '';

  for (const char of text) {
    current += char;
    if (/[，。、；：！？]/.test(char)) {
      segments.push(current);
      current = '';
    }
  }

  // Add remaining text if any
  if (current.trim()) {
    segments.push(current);
  }

  return segments;
}
